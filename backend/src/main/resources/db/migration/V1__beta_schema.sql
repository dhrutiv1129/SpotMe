CREATE TABLE beta_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE beta_sessions (
 token_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES beta_users(id) ON DELETE CASCADE,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX beta_sessions_expiry ON beta_sessions(expires_at);
CREATE TABLE beta_exercises (
 id BIGINT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 muscle_group VARCHAR(50) NOT NULL,
 equipment VARCHAR(50) NOT NULL,
 difficulty VARCHAR(20) NOT NULL,
 bodyweight BOOLEAN NOT NULL,
 instructions VARCHAR(1000) NOT NULL
);
CREATE TABLE beta_alternatives (
 original_id BIGINT NOT NULL REFERENCES beta_exercises(id),
 alternative_id BIGINT NOT NULL REFERENCES beta_exercises(id),
 relevance INTEGER NOT NULL CHECK (relevance BETWEEN 0 AND 100),
 PRIMARY KEY(original_id, alternative_id)
);
CREATE TABLE beta_workouts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES beta_users(id),
 workout_date DATE NOT NULL,
 request_key VARCHAR(80) NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 UNIQUE(user_id, request_key)
);
CREATE INDEX beta_workouts_owner_date ON beta_workouts(user_id, workout_date);
CREATE TABLE beta_sets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workout_id BIGINT NOT NULL REFERENCES beta_workouts(id) ON DELETE CASCADE,
 exercise_id BIGINT NOT NULL REFERENCES beta_exercises(id),
 exercise_position INTEGER NOT NULL,
 set_position INTEGER NOT NULL,
 reps INTEGER NOT NULL CHECK (reps > 0),
 weight DECIMAL(16,6) NOT NULL CHECK (weight >= 0),
 UNIQUE(workout_id, exercise_position, set_position)
);
